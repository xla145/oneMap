"""Application runtimes in the results shell; run only against an isolated QA DB."""
import prototype.test.check_integration_browser as b
b.SESSION='apps-check'
b.browser('open',b.BASE)
b.browser('set','viewport','1440','1000')
b.page('admin/integration-results?tab=scenes&theme=耕地保护和国土绿化空间')
b.click('[data-action=ig-open][data-id="app:app_cropland"]')
b.wait('document.querySelector("[name=scene]")?.value==="scene_cropland"')
assert b.ev('!!document.querySelector(".mw-header")&&!document.querySelector(".portal-site")')
b.click('[data-action=ig-tab][data-id=tools]')
b.wait('!!document.querySelector("#mt-choice")')
assert b.ev('document.querySelectorAll(".pc-ol-target").length')==1
b.click('.mw-app-toolbar a')
b.wait('!!document.querySelector("#ig-result-search")')
assert 'theme=' in b.ev('location.hash')
b.page('admin/integration-results?tab=scenes')
b.click('[data-action=ig-open][data-id="app:app_project"]')
b.wait('!!document.querySelector("[data-action=pc-start-model]")')
b.click('[data-action=pc-start-model]')
b.fill('#pc-case-create [name=projectName]','一张图应用原页验收')
b.fill('#pc-case-create [name=area]','12')
b.fill('#pc-case-create [name=purpose]','独立QA数据库中的原页办理回归验证')
b.browser('select','#pc-case-create [name=caseRegion]','呼和浩特市')
b.click('#pc-case-create button:not([type])')
b.wait('!!document.querySelector("#mw-app-case .pc-case-flow")')
assert '/admin/integration-results?' in b.ev('location.hash')
assert 'case=' in b.ev('location.hash')
assert b.ev('!!document.querySelector(".mw-header")&&!document.querySelector(".portal-site")')
b.click('#mw-app-case .pc-detail-back a')
b.wait('!!document.querySelector("[data-action=pc-start-model]")')
b.click('.mw-app-toolbar a')
b.wait('!!document.querySelector("#ig-result-search")')
b.click('[data-action=ig-open][data-id="app:app_consult"]')
b.wait('!!document.querySelector("[data-action=pc-start-model]")')
b.click('[data-action=pc-start-model]')
b.wait('document.querySelector("#dialog").open')
assert '/admin/integration-results?' in b.ev('location.hash')
b.browser('click','#dialog [data-action=close]')
b.click('.mw-app-toolbar a')
b.wait('!!document.querySelector("#ig-result-search")')
b.click('[data-action=ig-open][data-id="app:app_agent"]')
b.wait('!!document.querySelector("#mw-app-chat")')
b.fill('#mw-app-question','查找耕地保护相关资源')
b.click('#mw-app-chat button')
b.wait('document.querySelectorAll(".mw-app-message").length===2')
assert b.ev('document.querySelector("#mw-app-chat-status").textContent')=='已完成'
assert b.ev('!!document.querySelector(".mw-header")&&!document.querySelector(".portal-site")')
b.browser('screenshot','/tmp/onemap-app-inline-desktop.png')
b.browser('set','viewport','390','844')
assert not b.ev('document.documentElement.scrollWidth>innerWidth')
b.browser('screenshot','/tmp/onemap-app-inline-mobile.png')
assert b.browser('errors') in ['', 'No errors']
print('Passed: scene uses shared map/tools, two workflow entries, create→case→return stays in workspace, agent chat, filter return, mobile, no errors.')
